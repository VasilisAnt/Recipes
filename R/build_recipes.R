# ---- 2. Helpers --------------------------------------------------------------

# Transliterate Greek -> ASCII for clean, URL-safe file/folder names
slugify <- function(x) {
  x |>
    stri_trans_general("Greek-Latin/BGN; Latin-ASCII") |>
    str_to_lower() |>
    str_replace_all("[^a-z0-9]+", "-") |>
    str_replace_all("(^-+|-+$)", "")
}

write_recipe_qmd <- function(recipe) {
  # Force every field to be treated as UTF-8, regardless of the system's
  # locale settings (this matters on Windows especially -- without it,
  # Greek text can get silently mangled when written to file if R's
  # native/system encoding isn't UTF-8).
  title <- recipe$title; Encoding(title) <- "UTF-8"
  category <- recipe$category; Encoding(category) <- "UTF-8"
  body <- recipe$body; Encoding(body) <- "UTF-8"
  source_url <- recipe$source
  if (!is.null(source_url)) Encoding(source_url) <- "UTF-8"

  favorite_label <- "Αγαπημένο"
  Encoding(favorite_label) <- "UTF-8"
  categories <- c(category, if (isTRUE(recipe$favorite)) favorite_label else NULL)
  categories_yaml <- paste0('"', categories, '"', collapse = ", ")

  cat_slug <- slugify(category)
  file_slug <- slugify(title)

  out_dir <- path("recipes", cat_slug)
  dir_create(out_dir)
  out_file <- path(out_dir, glue("{file_slug}.qmd"))

  title_escaped <- str_replace_all(title, '"', '\\"')

  source_label <- "Πηγή"
  Encoding(source_label) <- "UTF-8"
  if (!is.null(source_url) && nzchar(source_url)) {
    body <- glue("{body}\n\n{source_label}: [{source_url}]({source_url})")
  }

  content <- glue(
    "---\n",
    "title: \"{title_escaped}\"\n",
    "categories: [{categories_yaml}]\n",
    "---\n",
    "\n",
    "{body}\n"
  )

  write_lines(content, out_file)
  out_file
}

